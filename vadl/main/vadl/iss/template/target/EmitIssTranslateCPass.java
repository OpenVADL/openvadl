/**
 * Emits the target/gen-arch/translate.c includes the C files that contain the instruction
 * translation functions and are generated by the {@link EmitIssInsnTransCIncPass}.
 * It also contains the {@code gen_intermediate_code} function, called by QEMU as
 * entry point to start the TCG generation.
 */
public class EmitIssTranslateCPass extends IssTemplateRenderingPass {
  public EmitIssTranslateCPass(IssConfiguration configuration) {
    super(configuration);
  }

  @Override
  protected String issTemplatePath() {
    return "target/gen-arch/translate.c";
  }

  @Override
  protected Map<String, Object> createVariables(PassResults passResults,
                                                Specification specification) {
    var vars = super.createVariables(passResults, specification);
    var accessorRegistry = passResults.lastResultOf(IssRegisterAccessInfoRetrievalPass.class,
        IssAccessorRegistry.class);
    vars.put("insn_width", getInstructionWidth(specification));
    vars.put("mem_word_size", getMemoryWordSize(specification));
    vars.put("trans_includes", translationIncludes(passResults));
    vars.put("tcg_v_init_code", genRegInitCode(specification));
    vars.put("alias_accessors", renderAliasAccessors(accessorRegistry));
    vars.put("bi_endian_condition", renderBiEndianCondition(specification));
    return vars;
  }

  /**
   * Gets translate functions.
   */
  private List<String> translationIncludes(PassResults results) {
    var insnTransResult = results.lastResultOf(EmitIssInsnTransCIncPass.class,
        AbstractMultiTemplateRenderingPass.Result.class);
    return insnTransResult.emittedFiles().stream()
        .map(p -> {
          var nameCount = p.getNameCount();
          return p.subpath(nameCount - 2, nameCount).toString();
        })
        .toList();
  }

  private static Map<String, Object> getMemoryWordSize(Specification specification) {
    var wordSize = specification.isa().get().ownMemories().get(0).wordSize();
    return Map.of(
        "int", wordSize
    );
  }

  private static Map<String, Object> getInstructionWidth(Specification specification) {
    var refFormat = specification.isa().get().ownInstructions()
        .get(0).format();
    var width = refFormat.type().bitWidth();

    return switch (width) {
      case 8 -> Map.of(
          "short", "b",
          "int", 8
      );
      case 16 -> Map.of(
          "short", "uw",
          "int", 16
      );
      case 32 -> Map.of(
          "short", "l",
          "int", 32
      );
      case 64 -> Map.of(
          "short", "q",
          "int", 64
      );
      default -> throw error("Invalid instruction width", refFormat.identifier.location())
          .description(
              "The ISS generator requires that every instruction width "
                  + "is one of [8, 16, 32, 64], but found %s",
              width)
          .build();
    };
  }

  private String genRegInitCode(Specification specification) {
    var sb = new StringBuilderAppendable();
    var isa = specification.processor().get().isa();
    sb.indent();
    isa.registerTensors().stream()
        .filter(IssUtils::isTcgReg)
        .filter(Predicate.not(IssUtils::isLazyReg))
        .forEach(tensor -> {
          regInitCode(sb, tensor);
          sb.append("\n");
        });
    return sb.toString();
  }

  private String renderBiEndianCondition(Specification specification) {
    var isa = specification.processor().get().isa();
    var memories = isa.ownMemories();
    ensure(memories.size() == 1,
        () -> error("Only one memory definition is supported", isa));
    var condition = memories.getFirst().biEndianCondition();
    if (condition == null) {
      return "";
    }
    return new IssTbStaticExpressionCodeGen(
        getSingleNode(condition, ReturnNode.class).value()
    ).fetch();
  }

  private List<Map<String, Object>> renderAliasAccessors(IssAccessorRegistry accessorRegistry) {
    return accessorRegistry.aliasAccessors(RegInfo.AccessType.READ, RegInfo.BackendKind.TCG)
        .stream()
        .map(this::renderAliasAccessor)
        .toList();
  }

  private Map<String, Object> renderAliasAccessor(AliasAccessorDescriptor descriptor) {
    var alias = descriptor.alias();
    var base = alias.semantics().baseTensor();
    var dims = descriptor.accessorArgs().stream()
        .map(arg -> Map.of(
            "size", arg.size(),
            "index_ctype", arg.ctype(),
            "arg_name", arg.name()))
        .toList();
    var forwardArgs = renderBaseForwardArgs(descriptor);
    var slice = alias.semantics().aliasSlice();
    var zeroCheck = renderZeroCheck(descriptor.zeroGuard(), descriptor.accessorArgs());
    return Map.ofEntries(
        Map.entry("name_lower", descriptor.accessorBaseName()),
        Map.entry("base_name_lower", base.simpleName().toLowerCase()),
        Map.entry("getter_params", renderAccessorParams(descriptor.accessorArgs())),
        Map.entry("index_dims", dims),
        Map.entry("value_width", descriptor.owner().renderObj().get("value_width")),
        Map.entry("alias_value_width", alias.resultType().bitWidth()),
        Map.entry("has_slice", slice != null),
        Map.entry("slice_lsb", slice == null ? 0 : slice.lsb()),
        Map.entry("slice_width", slice == null ? alias.resultType().bitWidth() : slice.bitSize()),
        Map.entry("zero_check", zeroCheck == null ? "" : zeroCheck),
        Map.entry("has_zero_check", zeroCheck != null),
        Map.entry("forward_args", forwardArgs)
    );
  }

  private String renderAccessorParams(List<RegInfo.AccessorArg> args) {
    var params = args.stream()
        .map(arg -> arg.ctype() + " " + arg.name())
        .collect(Collectors.joining(", "));
    return params.isEmpty() ? "" : ", " + params;
  }

  private String renderBaseForwardArgs(AliasAccessorDescriptor descriptor) {
    var args = descriptor.baseArgBindings().stream()
        .map(binding -> {
          if (binding instanceof RegInfo.FixedArgBinding fixed) {
            return "((" + CppTypeMap.nextFittingUInt(fixed.value().type()) + ") "
                + fixed.value().hexadecimal() + " )";
          }
          var forwarded = (RegInfo.ForwardedArgBinding) binding;
          return descriptor.accessorArgs().get(forwarded.accessorArgIndex()).name();
        })
        .collect(Collectors.joining(", "));
    return args.isEmpty() ? "" : ", " + args;
  }

  private @Nullable String renderZeroCheck(@Nullable RegInfo.ZeroGuard guard,
                                           List<RegInfo.AccessorArg> args) {
    if (guard == null) {
      return null;
    }
    if (guard instanceof RegInfo.AlwaysZeroGuard) {
      return "1";
    }
    var conditional = (RegInfo.ConditionalZeroGuard) guard;
    return conditional.matches().stream()
        .map(match -> args.get(match.accessorArgIndex()).name() + " == "
            + match.value().intValue())
        .collect(Collectors.joining(" && "));
  }

  private void regInitCode(CodeGeneratorAppendable sb, RegisterTensor reg) {
    var layers = reg.indexDimensions().stream()
        .map(d -> Pair.of("d" + d.index(), d.size()))
        .toList();
    var tcgIndexAccess = layers.stream().map(l -> "[" + l.left() + "]")
        .collect(Collectors.joining());

    var nameLower = reg.simpleName().toLowerCase();
    var targetUpper = configuration().targetName().toUpperCase();

    IssRenderUtils.generateNestedLoops(sb, layers, (b) -> {
      if (layers.isEmpty()) {
        b.append(
            "cpu_" + nameLower + " = tcg_global_mem_new(tcg_env, offsetof(CPU" + targetUpper
                + "State, " + nameLower + "), \"" + reg.simpleName() + "\");");
      } else {
        var target = configuration().targetName().toLowerCase();
        var names = target + "_cpu_" + nameLower + "_names";

        for (var c : reg.constraints()) {
          var check = genInitConstraintCheck(reg, c);
          b.appendLn("if (" + check + ") continue;");
        }

        var regInfo = reg.expectExtension(RegInfo.class);
        var cpuIndexAccess = regInfo.cArrayIndex("d");

        // cpu_x[i] = tcg_global_mem_new(tcg_env,
        //       offsetof(CPURV64IMState, x[i]),
        //       rv64im_cpu_x_names[i]);
        b.append("cpu_" + nameLower + tcgIndexAccess + "= tcg_global_mem_new(tcg_env, ")
            .append("offsetof(CPU" + targetUpper + "State, " + nameLower + cpuIndexAccess + "), ")
            .append(names + tcgIndexAccess + ");");
      }
    });
  }

  private String genInitConstraintCheck(RegisterTensor reg,
                                        RegisterResource.Constraint constraint) {
    return Streams.zip(constraint.indices().stream(),
            reg.indexDimensions().stream().limit(constraint.indices().size()),
            (index, dimension) -> "d" + dimension.index() + " == " + index.intValue())
        .collect(Collectors.joining(" && "));

  }


}
