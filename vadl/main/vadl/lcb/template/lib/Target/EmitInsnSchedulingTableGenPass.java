package vadl.lcb.template.lib.Target;

import static vadl.viam.ViamError.ensureNonNull;

import java.io.IOException;
import java.util.Map;
import vadl.configuration.GeneralConfiguration;
import vadl.lcb.passes.llvmLowering.LlvmSchedLoweringPass;
import vadl.lcb.template.LcbTemplateRenderingPass;
import vadl.pass.PassResults;
import vadl.viam.Specification;

/**
 * Generates a llvm-readable .td TableGen file containing the LLVM Machine
 * Scheduling Model. This is done based on the data gathered / generated by a
 * preceding run of {@link vadl.lcb.passes.llvmLowering.LlvmSchedLoweringPass}.
 */
public class EmitInsnSchedulingTableGenPass extends LcbTemplateRenderingPass {

  public EmitInsnSchedulingTableGenPass(GeneralConfiguration configuration) throws IOException {
    super(configuration);
  }

  @Override
  protected String getTemplatePath() {
    return "lcb/llvm/lib/Target/Sched.td";
  }

  @Override
  protected String getOutputPath() {

    var target = lcbConfiguration().targetName().value();

    return "llvm/lib/Target/" + target + "/" + target + "Sched.td";
  }

  @Override
  protected Map<String, Object> createVariables(
      PassResults passResults,
      Specification specification
  ) {
    final var llvmSchedLoweringPassResult = (LlvmSchedLoweringPass.Result) ensureNonNull(
        passResults.lastResultOf(LlvmSchedLoweringPass.class),
        "llvmSchedLowering must exist"
    );

    return Map.of(
        "schedWrites", llvmSchedLoweringPassResult.schedWrites(),
        "schedReads", llvmSchedLoweringPassResult.schedReads(),
        "writeRess", llvmSchedLoweringPassResult.writeRess(),
        "procResources", llvmSchedLoweringPassResult.procResources()
    );
  }
}
